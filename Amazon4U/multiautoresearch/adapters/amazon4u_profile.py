"""Profiling P4: private dataset, bundle, approval, ledger and launch for the
Musical_Instruments profiling run, beside the accepted GPU-READY adapter.

The GPU-READY adapter stays unchanged; this module reuses its file, ledger and transport
helpers. What differs:

- the data come from a private Kaggle dataset, named in `dataset_sources` and pinned by
  the SHA-256 of its `profiling-data-manifest.json`. The kernel finds the one mounted
  directory whose manifest has that hash, and the runner checks every file against it;
- before any push, the dataset is checked to be ready and private on Kaggle;
- the approval binds the bundle manifest, the dataset reference and the dataset manifest;
- runs book against their own ledger in data/reports/profiling-mi-v1/runs/, separate
  from GPU-READY's;
- outputs are `result.json` and `progress.jsonl`; the result must match its journal.

Usage:
  python -m multiautoresearch.adapters.amazon4u_profile upload-dir --dataset <staged dir> \\
      --slug <dataset slug> --out <fresh dir>
  python -m multiautoresearch.adapters.amazon4u_profile create-dataset --dir <upload dir> \\
      --kaggle <kaggle executable>
  python -m multiautoresearch.adapters.amazon4u_profile bundle --run 1 \\
      --dataset-ref <owner/slug> --manifest-sha256 <sha> --out <fresh dir>
  python -m multiautoresearch.adapters.amazon4u_profile launch --bundle <dir> \\
      --approval <file> --kaggle <kaggle executable>
"""

