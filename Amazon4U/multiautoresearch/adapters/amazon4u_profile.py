KERNEL_TEMPLATE = '''"""Amazon4U Musical_Instruments profiling run {run}. Generated by amazon4u_profile.py; do not edit."""
import base64
import gzip
import hashlib
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

SOURCES = json.loads({sources!r})
MANIFEST_SHA256 = "{manifest_sha}"
RUNNER_TIMEOUT_SECONDS = {runner_timeout}


def hydrate(root):
    for rel, (digest, packed) in sorted(SOURCES.items()):
        data = gzip.decompress(base64.b64decode(packed))
        if hashlib.sha256(data).hexdigest() != digest:
            raise SystemExit(f"source hash mismatch: {{rel}}")
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "xb") as f:
            f.write(data)


def find_dataset(base):
    found = [p.parent for p in base.rglob("{manifest_name}")
             if hashlib.sha256(p.read_bytes()).hexdigest() == MANIFEST_SHA256]
    if len(found) != 1:
        raise SystemExit(f"expected one dataset with the pinned manifest; found {{len(found)}}")
    return found[0]


def main(device="cuda:0", accelerator="gpu", out=Path("/kaggle/working"),
         inputs=Path("/kaggle/input")):
    # Sources go outside /kaggle/working, so the collected output holds only the run's files.
    root = Path(tempfile.mkdtemp(prefix="amazon4u-src-"))
    hydrate(root)
    data = find_dataset(inputs)
    env = {{**os.environ, "CUDA_VISIBLE_DEVICES": "0", "CUBLAS_WORKSPACE_CONFIG": ":4096:8",
           "PYTHONDONTWRITEBYTECODE": "1"}}
    code = subprocess.run(
        [sys.executable, "-m", "scripts.profiling_runner", "--device", device,
         "--accelerator", accelerator, "--data", str(data), "--manifest-sha256", MANIFEST_SHA256,
         "--out-dir", str(out)],
        cwd=root, env=env, timeout=RUNNER_TIMEOUT_SECONDS).returncode
    if not (out / "{result}").exists():
        raise SystemExit(f"runner exited {{code}} without a result")
    print(json.dumps({{"runner_exit_code": code}}))


if __name__ == "__main__":
    main()
'''


def build_upload_dir(dataset_dir, out_dir, *, slug, manifest_sha256, owner=OWNER):
    """Copy a verified staged dataset and add Kaggle's dataset-metadata.json (private)."""
    if not _SLUG.fullmatch(slug):
        raise Amazon4UError(f'dataset slug {slug!r} must be 6 to 50 lowercase letters, digits or -')
    dataset_dir, out_dir = Path(dataset_dir), Path(out_dir)
    manifest = verify_dataset(dataset_dir, manifest_sha256)
    out_dir.mkdir(mode=0o700)
    for name in [*manifest['files'], MANIFEST_NAME]:
        shutil.copyfile(dataset_dir / name, out_dir / name)
    metadata = {'title': slug, 'id': f'{owner}/{slug}', 'isPrivate': True,
                'licenses': [{'name': 'unknown'}],
                'description': 'Amazon4U Musical_Instruments profiling inputs: KG-v1 parquet, '
                               'train and validation splits. Private. No test split. Source: '
                               f'{SOURCE_DATASET}'}
    (out_dir / KAGGLE_METADATA_NAME).write_bytes(_canonical(metadata))
    verify_dataset(out_dir, manifest_sha256)
    return metadata['id']


class KaggleDatasetCli:
    """`datasets create`, `status` and `metadata` as argv subprocesses; never `--public`."""

    def __init__(self, executable, *, command_timeout=600, run=subprocess.run):
        self.executable, self.command_timeout, self._run = str(executable), command_timeout, run

    def _call(self, *args):
        return self._run([self.executable, *args], capture_output=True, text=True,
                         timeout=self.command_timeout, stdin=subprocess.DEVNULL, check=False)

    def create(self, upload_dir):
        meta = json.loads((Path(upload_dir) / KAGGLE_METADATA_NAME).read_text())
        if meta.get('isPrivate') is not True:
            raise Amazon4UError('dataset metadata must be private; create refused')
        out = self._call('datasets', 'create', '-p', str(upload_dir), '-r', 'skip', '-q')
        if out.returncode != 0:
            raise Amazon4UError(f'datasets create failed: {_message(out)!r}')
        return meta['id']

    def require_ready_and_private(self, dataset_ref):
        """Refuse unless Kaggle reports the dataset ready and its metadata says private.

        The CLI writes the server's metadata, which omits `isPrivate` when it is false, so
        only an explicit `true` counts."""
        out = self._call('datasets', 'status', dataset_ref)
        if out.returncode != 0 or out.stdout.strip() != 'ready':
            raise Amazon4UError(f'dataset {dataset_ref} is not ready: {_message(out)!r}')
        with tempfile.TemporaryDirectory() as tmp:
            out = self._call('datasets', 'metadata', dataset_ref, '-p', tmp)
            path = Path(tmp) / KAGGLE_METADATA_NAME
            if out.returncode != 0 or not path.is_file():
                raise Amazon4UError(f'dataset metadata unavailable: {_message(out)!r}')
            meta = json.loads(path.read_text())
        meta = meta.get('info', meta)
        if meta.get('isPrivate') is not True:
            raise Amazon4UError(f'dataset {dataset_ref} is not verified private; launch refused')
        return {'status': 'ready', 'isPrivate': True}


def bundle_sources(root=ROOT):
    """Every scripts/ and tests/ Python file: the set `bundle_digest` covers."""
    paths = sorted([*root.glob('scripts/*.py'), *root.glob('tests/*.py')])
    return {p.relative_to(root).as_posix(): p.read_bytes() for p in paths}


def expected_binding(sources, manifest_sha256):
    """The run binding the runner will compute inside the kernel from these sources."""
    with tempfile.TemporaryDirectory() as tmp:
        for rel, data in sources.items():
            path = Path(tmp) / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        bundle = bundle_digest(Path(tmp))
    return {'bundle_sha256': bundle, 'dataset_manifest_sha256': manifest_sha256}


def build_bundle(run, dataset_ref, manifest_sha256, out_dir, *, root=ROOT):
    """Write kernel.py, kernel-metadata.json and bundle.json into a new directory."""
    if type(run) is not int or not 1 <= run <= MAX_RUNS:
        raise Amazon4UError(f'run must be 1 to {MAX_RUNS}')
    if not _SHA.fullmatch(manifest_sha256):
        raise Amazon4UError('dataset manifest SHA-256 must be 64 lowercase hex characters')
    owner, _, dslug = dataset_ref.partition('/')
    if owner != OWNER or not _SLUG.fullmatch(dslug):
        raise Amazon4UError(f'dataset must be {OWNER}/<slug>')
    out_dir = Path(out_dir)
    sources = bundle_sources(root)
    binding = expected_binding(sources, manifest_sha256)
    slug = f'amazon4u-profile-mi-run-{run}-{binding["bundle_sha256"][:8]}'
    packed = {rel: [_sha256(data), base64.b64encode(gzip.compress(data, mtime=0)).decode()]
              for rel, data in sources.items()}
    kernel = KERNEL_TEMPLATE.format(
        run=run, sources=json.dumps(packed, sort_keys=True), manifest_sha=manifest_sha256,
        runner_timeout=RUNNER_PROCESS_TIMEOUT_SECONDS, manifest_name=MANIFEST_NAME,
        result=RESULT_NAME).encode()
    metadata = _canonical({
        'id': f'{OWNER}/{slug}', 'title': slug, 'code_file': 'kernel.py', 'language': 'python',
        'kernel_type': 'script', 'is_private': True, 'enable_gpu': True, 'enable_tpu': False,
        'enable_internet': False, 'dataset_sources': [dataset_ref], 'competition_sources': [],
        'kernel_sources': [], 'model_sources': [],
    })
    manifest = {
        'schema_version': SCHEMA_BUNDLE, 'run': run, 'kernel_ref': f'{OWNER}/{slug}',
        'dataset_ref': dataset_ref, 'dataset_manifest_sha256': manifest_sha256,
        'accelerator': ACCELERATOR, 'timeout_seconds': SESSION_TIMEOUT_SECONDS,
        'max_runs': MAX_RUNS, 'max_total_gpu_seconds': MAX_TOTAL_GPU_SECONDS,
        'max_output_bytes': MAX_OUTPUT_BYTES, 'run_binding': binding,
        'kernel_sha256': _sha256(kernel), 'metadata_sha256': _sha256(metadata),
        'files': {rel: {'sha256': _sha256(data), 'size_bytes': len(data)}
                  for rel, data in sorted(sources.items())},
        'git': _git_state(root),
    }
    out_dir.mkdir(parents=True, exist_ok=False)
    (out_dir / 'kernel.py').write_bytes(kernel)
    (out_dir / 'kernel-metadata.json').write_bytes(metadata)
    (out_dir / 'bundle.json').write_bytes(_canonical(manifest))
    return manifest


def load_bundle(bundle_dir):
    """The manifest and its SHA-256, after checking kernel and metadata against it."""
    bundle_dir = Path(bundle_dir)
    raw = _read_regular(bundle_dir / 'bundle.json', MAX_RESULT_BYTES)
    manifest = json.loads(raw)
    if manifest.get('schema_version') != SCHEMA_BUNDLE:
        raise Amazon4UError('not a profiling bundle manifest')
    for name, key in (('kernel.py', 'kernel_sha256'), ('kernel-metadata.json', 'metadata_sha256')):
        if _sha256(_read_regular(bundle_dir / name, MAX_RESULT_BYTES)) != manifest[key]:
            raise Amazon4UError(f'{name} differs from the bundle manifest')
    meta = json.loads((bundle_dir / 'kernel-metadata.json').read_bytes())
    if (meta['id'] != manifest['kernel_ref'] or meta['is_private'] is not True
            or meta['enable_gpu'] is not True or meta['enable_internet'] is not False
            or meta['dataset_sources'] != [manifest['dataset_ref']]):
        raise Amazon4UError('kernel metadata must be private, GPU-enabled, offline and use '
                            'only the bundle dataset')
    return manifest, _sha256(raw)


def validate_approval(approval, manifest, manifest_sha):
    """The user's per-run approval, bound to this bundle and this dataset."""
    if type(approval) is not dict or set(approval) != APPROVAL_KEYS:
        raise Amazon4UError('approval keys must be exactly ' + ', '.join(sorted(APPROVAL_KEYS)))
    if approval['schema_version'] != SCHEMA_APPROVAL or approval['approved_by'] != 'user':
        raise Amazon4UError('approval must be a user profiling run approval')
    for key, want in (('run', manifest['run']), ('kernel_ref', manifest['kernel_ref']),
                      ('bundle_manifest_sha256', manifest_sha),
                      ('dataset_ref', manifest['dataset_ref']),
                      ('dataset_manifest_sha256', manifest['dataset_manifest_sha256'])):
        if approval[key] != want:
            raise Amazon4UError(f'approval {key} does not match the bundle; launch refused')
    if type(approval['statement']) is not str or not approval['statement'].strip():
        raise Amazon4UError('approval must quote the user statement')


def _check_result(result, journal_path, manifest):
    validate_result(result, journal_path)
    env = result['environment']
    if result['run_binding'] != manifest['run_binding']:
        raise Amazon4UError('result run binding differs from the pushed bundle')
    if env['device'] != 'cuda:0' or env['used_device_count'] != 1 or env['visible_device_count'] < 1:
        raise Amazon4UError('result must come from exactly one GPU, cuda:0')
    if result['determinism'] != EXPECTED_DETERMINISM:
        raise Amazon4UError('result determinism differs from the fixed policy')
    if (result['limits'] != asdict(AGREED_LIMITS)
            or result['cases_planned'] != [list(c) for c in CASES]):
        raise Amazon4UError('result limits or cases differ from the agreed plan')


def collect_profile_outputs(download_dir, dest, *, manifest, record_fields, log,
                            check=None, gates=REMAINING_GATES):
    """Check one downloaded output directory, add the record and move it to `dest`.

    `check(result, journal_path, manifest)` refuses a bad result; it defaults to the
    profiling result's checks."""
    check = check or _check_result
    download_dir, dest = Path(download_dir), Path(dest)
    if dest.exists():
        raise Amazon4UError(f'{dest} already exists; overwrite refused')
    raw_log = f'{manifest["kernel_ref"].split("/")[1]}.log'
    names = set(os.listdir(download_dir))
    if not {RESULT_NAME, JOURNAL_NAME} <= names <= {RESULT_NAME, JOURNAL_NAME, raw_log}:
        raise Amazon4UError(f'outputs must be {RESULT_NAME}, {JOURNAL_NAME} and the kernel log; '
                            f'got {sorted(names)}')
    total = 0
    for name in names:
        info = os.lstat(download_dir / name)
        if not stat.S_ISREG(info.st_mode):
            raise Amazon4UError(f'{name} is not a regular file')
        total += info.st_size
    if total > manifest['max_output_bytes']:
        raise Amazon4UError(f'outputs exceed {manifest["max_output_bytes"]} bytes')
    raw_result = _read_regular(download_dir / RESULT_NAME, MAX_RESULT_BYTES)
    raw_journal = _read_regular(download_dir / JOURNAL_NAME, MAX_RESULT_BYTES)
    result = json.loads(raw_result)
    check(result, download_dir / JOURNAL_NAME, manifest)
    if raw_log in names:
        os.unlink(download_dir / raw_log)
    log_bytes = log['logs'].encode()
    with open(download_dir / LOG_NAME, 'xb') as f:
        f.write(log_bytes)
    record = {
        **record_fields, 'schema_version': SCHEMA_RECORD,
        'files': {RESULT_NAME: {'sha256': _sha256(raw_result), 'size_bytes': len(raw_result)},
                  JOURNAL_NAME: {'sha256': _sha256(raw_journal), 'size_bytes': len(raw_journal)},
                  LOG_NAME: {'sha256': _sha256(log_bytes), 'size_bytes': len(log_bytes),
                             'consumer_status': log['status']}},
        'run_binding': manifest['run_binding'], 'environment': result['environment'],
        'result_status': result['status'], 'stop_reason': result['stop_reason'],
        'acceptance': 'requires_user_review', 'deployment_decision': 'NOT_AUTHORIZED',
        'remaining_gates': list(gates),
    }
    with open(download_dir / 'record.json', 'xb') as f:
        f.write(_canonical(record))
    atomic_move_no_replace(download_dir, dest)
    return record


def launch(bundle_dir, approval_path, transport, datasets, *, reports=REPORTS,
           clock=time.monotonic, sleep=time.sleep, collect=None):
    """Approved push, bounded wait, collection and record for one run; never retried.

    `collect` checks and files the downloaded outputs; it defaults to the profiling
    result's `collect_profile_outputs` (the checkpoint proof passes its own)."""
    collect = collect or collect_profile_outputs
    manifest, manifest_sha = load_bundle(bundle_dir)
    approval_raw = _read_regular(Path(approval_path), 65536)
    validate_approval(json.loads(approval_raw), manifest, manifest_sha)
    run, ref = manifest['run'], manifest['kernel_ref']
    owner, slug = ref.split('/')
    if not 1 <= run <= manifest['max_runs']:
        raise Amazon4UError(f'run {run} is outside the budget of {manifest["max_runs"]} runs')
    reports = Path(reports)
    reports.mkdir(parents=True, exist_ok=True)
    booked = gpu_ledger(reports)
    if booked + manifest['timeout_seconds'] > manifest['max_total_gpu_seconds']:
        raise Amazon4UError(f'GPU budget: {booked} s booked plus {manifest["timeout_seconds"]} s '
                            f'exceeds {manifest["max_total_gpu_seconds"]} s; launch refused')
    transport.require_cli_version()
    privacy = datasets.require_ready_and_private(manifest['dataset_ref'])
    fields = {'run': run, 'kernel_ref': ref, 'bundle_manifest_sha256': manifest_sha,
              'dataset_ref': manifest['dataset_ref'],
              'dataset_manifest_sha256': manifest['dataset_manifest_sha256'],
              'dataset_check': privacy, 'approval_sha256': _sha256(approval_raw),
              'booked_gpu_seconds': manifest['timeout_seconds'],
              'gpu_seconds_booked_before': booked}
    _write_once(reports / f'run-{run}.reserved.json', fields)

    def fail(stage, reason, **extra):
        _write_once(reports / f'run-{run}.failure.json', {**fields, 'stage': stage, 'reason': reason, **extra})
        raise Amazon4UError(f'run {run} failed at {stage}: {reason}')

    try:
        receipt = transport.push(Path(bundle_dir), timeout=manifest['timeout_seconds'],
                                 accelerator=ACCELERATOR, plan_digest=manifest_sha)
    except SubmissionUnknownError as exc:
        fail('push', f'submission_unknown: {exc}; automatic re-push is prohibited')
    try:
        validate_submission_receipt(receipt, expected_owner=owner, expected_slug=slug,
                                    expected_version=1, expected_timeout=manifest['timeout_seconds'],
                                    expected_accelerator=ACCELERATOR, expected_plan_digest=manifest_sha)
    except Amazon4UError as exc:
        fail('receipt', str(exc))
    deadline = manifest['timeout_seconds'] + QUEUE_MARGIN_SECONDS
    status = poll_kernel_status(ref, 1, transport, max_polls=deadline // POLL_INTERVAL_SECONDS + 1,
                                deadline_seconds=deadline, poll_interval=POLL_INTERVAL_SECONDS,
                                clock_fn=clock, sleep_fn=sleep)
    receipt_fields = {k: receipt[k] for k in ('version_ref', 'acknowledged_version', 'timeout',
                                               'accelerator', 'url')}
    if status not in ('complete', 'error'):
        fail('status', status, receipt=receipt_fields)
    try:
        download = transport.download_outputs(ref, reports)
    except Amazon4UError as exc:
        fail('download', str(exc), receipt=receipt_fields, terminal_status=status)
    log = consume_kernel_logs(ref, 1, transport, max_bytes=MAX_LOG_BYTES)
    if status != 'complete':
        fail('status', status, receipt=receipt_fields, download=str(download), log_status=log['status'])
    try:
        return collect(download, reports / f'run-{run}', manifest=manifest, log=log,
                       record_fields={**fields, 'receipt': receipt_fields,
                                      'terminal_status': status})
    except (Amazon4UError, OSError, ValueError, KeyError) as exc:
        fail('collection', str(exc), download=str(download))


def main(argv=None):
    parser = argparse.ArgumentParser(prog='amazon4u_profile')
    sub = parser.add_subparsers(dest='command', required=True)
    u = sub.add_parser('upload-dir')
    u.add_argument('--dataset', required=True)
    u.add_argument('--manifest-sha256', required=True)
    u.add_argument('--slug', required=True)
    u.add_argument('--out', required=True)
    c = sub.add_parser('create-dataset')
    c.add_argument('--dir', required=True)
    c.add_argument('--kaggle', required=True)
    v = sub.add_parser('check-dataset')
    v.add_argument('--dataset-ref', required=True)
    v.add_argument('--kaggle', required=True)
    b = sub.add_parser('bundle')
    b.add_argument('--run', type=int, required=True)
    b.add_argument('--dataset-ref', required=True)
    b.add_argument('--manifest-sha256', required=True)
    b.add_argument('--out', required=True)
    lp = sub.add_parser('launch')
    lp.add_argument('--bundle', required=True)
    lp.add_argument('--approval', required=True)
    lp.add_argument('--kaggle', required=True)
    lp.add_argument('--reports', default=str(REPORTS))
    args = parser.parse_args(argv)
    if args.command == 'upload-dir':
        print(build_upload_dir(args.dataset, args.out, slug=args.slug,
                               manifest_sha256=args.manifest_sha256))
        return 0
    if args.command == 'create-dataset':
        print(KaggleDatasetCli(args.kaggle).create(args.dir))
        return 0
    if args.command == 'check-dataset':
        print(json.dumps(KaggleDatasetCli(args.kaggle).require_ready_and_private(args.dataset_ref)))
        return 0
    if args.command == 'bundle':
        manifest = build_bundle(args.run, args.dataset_ref, args.manifest_sha256, args.out)
        _, manifest_sha = load_bundle(args.out)
        print(json.dumps({'schema_version': SCHEMA_APPROVAL, 'run': manifest['run'],
                          'kernel_ref': manifest['kernel_ref'],
                          'bundle_manifest_sha256': manifest_sha,
                          'dataset_ref': manifest['dataset_ref'],
                          'dataset_manifest_sha256': manifest['dataset_manifest_sha256'],
                          'approved_by': 'user', 'approved_on': '<YYYY-MM-DD>',
                          'statement': '<the user approval, quoted>'}, indent=2))
        return 0
    from multiautoresearch.adapters.amazon4u_kaggle import KaggleCliTransport
    record = launch(args.bundle, args.approval, KaggleCliTransport(args.kaggle),
                    KaggleDatasetCli(args.kaggle), reports=args.reports)
    print(json.dumps({'run': record['run'], 'result_status': record['result_status']}))
    return 0


if __name__ == '__main__':
    sys.exit(main())
