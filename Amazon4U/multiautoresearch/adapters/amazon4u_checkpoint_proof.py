"""Checkpoint readiness C4: bundle and launch the real-data checkpoint proof on Kaggle.

The proof is booked in the profiling ledger (user decision, 2026-10-25: "use the profiling
ledger"), so it reuses the profiling adapter's bundle format, per-run approval, ledger,
dataset privacy check, push and polling unchanged. What differs:

- the kernel runs `scripts.checkpoint_proof` instead of the profiling runner;
- the bundle's run binding is the proof's checkpoint binding (source bundle and plan);
- collection checks a proof result: its journal, the binding, one GPU at cuda:0, the
  fixed determinism policy in every child process, and the agreed plan.

Usage:
  python -m multiautoresearch.adapters.amazon4u_checkpoint_proof bundle --run 3 \\
      --dataset-ref <owner/slug> --manifest-sha256 <sha> --out <fresh dir>
  python -m multiautoresearch.adapters.amazon4u_checkpoint_proof launch --bundle <dir> \\
      --approval <file> --kaggle <kaggle executable>
"""

from __future__ import annotations

import argparse
import base64
import functools
import gzip
import json
import sys
import tempfile
from pathlib import Path

from multiautoresearch.adapters.amazon4u import Amazon4UError
from multiautoresearch.adapters.amazon4u_gpu import ACCELERATOR, OWNER, _canonical, _git_state, _sha256
from multiautoresearch.adapters.amazon4u_profile import (
    KERNEL_TEMPLATE, MAX_OUTPUT_BYTES, MAX_RUNS, MAX_TOTAL_GPU_SECONDS, REPORTS,
    RUNNER_PROCESS_TIMEOUT_SECONDS, SCHEMA_APPROVAL, SCHEMA_BUNDLE, SESSION_TIMEOUT_SECONDS,
    KaggleDatasetCli, _SHA, _SLUG, bundle_sources, collect_profile_outputs, launch, load_bundle,
)
from scripts import checkpoint_proof
from scripts.gpu_runtime import EXPECTED_DETERMINISM
from scripts.profiling_data import MANIFEST_NAME

ROOT = Path(__file__).resolve().parents[2]
PROFILE_RUNNER = '"-m", "scripts.profiling_runner"'
PROFILE_TITLE = 'Amazon4U Musical_Instruments profiling run {run}. Generated by amazon4u_profile.py'
if PROFILE_RUNNER not in KERNEL_TEMPLATE or PROFILE_TITLE not in KERNEL_TEMPLATE:
    raise ImportError('profiling kernel template changed; the proof kernel cannot be derived')
PROFILE_OUT = '"--out-dir", str(out)]'
if PROFILE_OUT not in KERNEL_TEMPLATE:
    raise ImportError('profiling kernel template changed; the proof kernel cannot be derived')
KERNEL = (KERNEL_TEMPLATE
          .replace(PROFILE_RUNNER, '"-m", "scripts.checkpoint_proof"')
          .replace(PROFILE_OUT, '"--out-dir", str(out), "--version", "{version}"]')
          .replace(PROFILE_TITLE, 'Amazon4U checkpoint proof run {run}. Generated by '
                                  'amazon4u_checkpoint_proof.py'))


def expected_binding(sources, manifest_sha256, version):
    """The checkpoint run binding the proof will compute inside the kernel."""
    with tempfile.TemporaryDirectory() as tmp:
        for rel, data in sources.items():
            path = Path(tmp) / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        return checkpoint_proof.run_binding(manifest_sha256, root=Path(tmp), version=version)


def build_bundle(run, dataset_ref, manifest_sha256, out_dir, *, root=ROOT, version=2):
    """kernel.py, kernel-metadata.json and bundle.json, in the profiling bundle format.

    Version 1 was run 2; new bundles default to identity v2 (run 3)."""
    if version not in checkpoint_proof.VERSIONS:
        raise Amazon4UError(f'checkpoint version must be one of {checkpoint_proof.VERSIONS}')
    if type(run) is not int or not 1 <= run <= MAX_RUNS:
        raise Amazon4UError(f'run must be 1 to {MAX_RUNS}')
    if not _SHA.fullmatch(manifest_sha256):
        raise Amazon4UError('dataset manifest SHA-256 must be 64 lowercase hex characters')
    owner, _, dslug = dataset_ref.partition('/')
    if owner != OWNER or not _SLUG.fullmatch(dslug):
        raise Amazon4UError(f'dataset must be {OWNER}/<slug>')
    out_dir = Path(out_dir)
    sources = bundle_sources(root)
    binding = expected_binding(sources, manifest_sha256, version)
    slug = f'amazon4u-ckpt-proof-mi-run-{run}-{binding["bundle_sha256"][:8]}'
    packed = {rel: [_sha256(data), base64.b64encode(gzip.compress(data, mtime=0)).decode()]
              for rel, data in sources.items()}
    kernel = KERNEL.format(
        run=run, sources=json.dumps(packed, sort_keys=True), manifest_sha=manifest_sha256,
        runner_timeout=RUNNER_PROCESS_TIMEOUT_SECONDS, manifest_name=MANIFEST_NAME,
        result=checkpoint_proof.RESULT_NAME, version=version).encode()
    metadata = _canonical({
        'id': f'{OWNER}/{slug}', 'title': slug, 'code_file': 'kernel.py', 'language': 'python',
        'kernel_type': 'script', 'is_private': True, 'enable_gpu': True, 'enable_tpu': False,
        'enable_internet': False, 'dataset_sources': [dataset_ref], 'competition_sources': [],
        'kernel_sources': [], 'model_sources': [],
    })
    manifest = {
        'schema_version': SCHEMA_BUNDLE, 'purpose': 'checkpoint_readiness_C4', 'run': run,
        'kernel_ref': f'{OWNER}/{slug}', 'dataset_ref': dataset_ref,
        'dataset_manifest_sha256': manifest_sha256, 'accelerator': ACCELERATOR,
        'timeout_seconds': SESSION_TIMEOUT_SECONDS, 'max_runs': MAX_RUNS,
        'max_total_gpu_seconds': MAX_TOTAL_GPU_SECONDS, 'max_output_bytes': MAX_OUTPUT_BYTES,
        'run_binding': binding, 'proof_plan': checkpoint_proof.plan(manifest_sha256, version=version),
        'kernel_sha256': _sha256(kernel), 'metadata_sha256': _sha256(metadata),
        'files': {rel: {'sha256': _sha256(data), 'size_bytes': len(data)}
                  for rel, data in sorted(sources.items())},
        'git': _git_state(root),
    }
    out_dir.mkdir(parents=True, exist_ok=False)
    (out_dir / 'kernel.py').write_bytes(kernel)
    (out_dir / 'kernel-metadata.json').write_bytes(metadata)
    (out_dir / 'bundle.json').write_bytes(_canonical(manifest))
    return manifest


def check_result(result, journal_path, manifest):
    checkpoint_proof.validate_result(result, journal_path)
    if manifest.get('purpose') != 'checkpoint_readiness_C4':
        raise Amazon4UError('not a checkpoint proof bundle')
    if result['run_binding'] != manifest['run_binding'] or result['plan'] != manifest['proof_plan']:
        raise Amazon4UError('result binding or plan differs from the pushed bundle')
    env = result['environment']
    if env['device'] != 'cuda:0' or env['used_device_count'] != 1 or env['visible_device_count'] < 1:
        raise Amazon4UError('result must come from exactly one GPU, cuda:0')
    for case in result['cases']:
        for record in case['children'].values():
            if 'child_error' not in record and (record['determinism'] != EXPECTED_DETERMINISM
                                                or record['environment'] != env):
                raise Amazon4UError('a child process ran outside the fixed policy or environment')


collect = functools.partial(collect_profile_outputs, check=check_result,
                            gates=checkpoint_proof.REMAINING_GATES)


def main(argv=None):
    parser = argparse.ArgumentParser(prog='amazon4u_checkpoint_proof')
    sub = parser.add_subparsers(dest='command', required=True)
    b = sub.add_parser('bundle')
    b.add_argument('--run', type=int, required=True)
    b.add_argument('--dataset-ref', required=True)
    b.add_argument('--manifest-sha256', required=True)
    b.add_argument('--out', required=True)
    lp = sub.add_parser('launch')
    lp.add_argument('--bundle', required=True)
    lp.add_argument('--approval', required=True)
    lp.add_argument('--kaggle', required=True)
    lp.add_argument('--reports', default=str(REPORTS))
    args = parser.parse_args(argv)
    if args.command == 'bundle':
        manifest = build_bundle(args.run, args.dataset_ref, args.manifest_sha256, args.out)
        _, manifest_sha = load_bundle(args.out)
        print(json.dumps({'schema_version': SCHEMA_APPROVAL, 'run': manifest['run'],
                          'kernel_ref': manifest['kernel_ref'],
                          'bundle_manifest_sha256': manifest_sha,
                          'dataset_ref': manifest['dataset_ref'],
                          'dataset_manifest_sha256': manifest['dataset_manifest_sha256'],
                          'approved_by': 'user', 'approved_on': '<YYYY-MM-DD>',
                          'statement': '<the user approval, quoted>'}, indent=2))
        return 0
    from multiautoresearch.adapters.amazon4u_kaggle import KaggleCliTransport
    record = launch(args.bundle, args.approval, KaggleCliTransport(args.kaggle),
                    KaggleDatasetCli(args.kaggle), reports=args.reports, collect=collect)
    print(json.dumps({'run': record['run'], 'result_status': record['result_status']}))
    return 0


if __name__ == '__main__':
    sys.exit(main())
