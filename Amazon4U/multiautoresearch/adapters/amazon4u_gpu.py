"""GR08: GPU-READY orchestration beside the accepted O-OFFLINE adapter.

The O-OFFLINE adapter stays unchanged. This module reuses only its device-independent
parts: the submission receipt check, status polling, log reading and the no-replace move.
O-OFFLINE's collection and bundle building are bound to H-REF records, so they are
replaced here (docs/gpu-ready-kaggle-execution.md, reuse audit).

Nothing is pushed without a per-run approval file bound to the exact bundle manifest.
Each run number is reserved once and never retried. Outputs are checked in a fresh
private download directory, then moved to data/reports/gpu-ready-v1/run-<n>/ without
replacing anything.

Usage:
  python -m multiautoresearch.adapters.amazon4u_gpu bundle --run 1 --out <fresh dir>
  python -m multiautoresearch.adapters.amazon4u_gpu launch --bundle <dir> \\
      --approval <file> --kaggle /home/sunf/miniconda3/bin/kaggle
"""

