"""Musical_Instruments comparative training on Kaggle: campaign plan, bundles and launch.

Settings and rules: docs/musical-instruments-training-settings.md and
docs/learning-rate-tuning-amendment.md (amazon4u-protocol-v2.1.0). The profiling
adapter's bundle format, dataset privacy check, push, polling and run directories are
reused unchanged. What differs:

- **One frozen campaign plan** (`campaign_plan()`). It holds 12 tuning runs (3 learning
  rates × 2 methods × 2 conditions, seed 42) and the final rule: for each method and
  condition, the learning rate with the best tuning validation NDCG@10 (exact ties
  earliest in 0.0005, 0.001, 0.002) is trained with seeds 2026 and 3407. Its tuning run is
  final seed 42. No run outside the plan can be bundled, and a final run can be bundled
  only once all three tuning runs of its group are collected.
- **Approval.** Either the profiling-style per-run approval, bound to one built bundle,
  or a campaign approval bound to the plan digest, the source bundle digest and the
  dataset. The campaign approval covers every planned run built from those exact sources.
  It is used only if the user approves it.
- **Ledger** in `data/reports/training-mi-v1/runs/`, capped at 24 GPU-hours. A reserved
  run counts its booking (measured worst case + 25 %) until it is collected. It then
  counts its recorded runner time plus a fixed session overhead.
- **Collection** checks `scripts.training_run.validate_result` and keeps `result.json`,
  the progress journals and `final.a4ucp`, which holds the best model.

Usage:
  python -m multiautoresearch.adapters.amazon4u_training plan
  python -m multiautoresearch.adapters.amazon4u_training bundle --run 1 --method LightGCN \\
      --condition all_ratings --learning-rate 0.001 --seed 42 --stage tuning \\
      --dataset-ref <owner/slug> --manifest-sha256 <sha> --out <fresh dir>
  python -m multiautoresearch.adapters.amazon4u_training launch --bundle <dir> \\
      --approval <file> --kaggle <kaggle executable>
"""

from __future__ import annotations

import argparse
import base64
import gzip
import hashlib
import json
import os
import stat
import sys
import tempfile
from pathlib import Path

from multiautoresearch.adapters.amazon4u import Amazon4UError, atomic_move_no_replace
from multiautoresearch.adapters.amazon4u_gpu import (
    ACCELERATOR, LOG_NAME, OWNER, _canonical, _git_state, _read_regular, _sha256, _write_once,
)
from multiautoresearch.adapters.amazon4u_profile import (
    KERNEL_TEMPLATE, SCHEMA_APPROVAL, SCHEMA_BUNDLE, KaggleDatasetCli, _SHA, _SLUG, bundle_sources,
    launch as profile_launch, load_bundle, validate_approval,
)
from scripts import training_run
from scripts.gpu_ready_parity import bundle_digest
from scripts.gpu_runtime import EXPECTED_DETERMINISM
from scripts.profiling_data import MANIFEST_NAME

ROOT = Path(__file__).resolve().parents[2]
REPORTS = ROOT / 'data/reports/training-mi-v1/runs'
SCHEMA_CAMPAIGN = 'amazon4u-training-campaign-v1'
SCHEMA_CAMPAIGN_APPROVAL = 'amazon4u-training-campaign-approval-v1'
SCHEMA_RECORD = 'amazon4u-training-record-v1'
METHODS = (training_run.LIGHTGCN, training_run.HETERO)
CONDITIONS = ('all_ratings', 'rating_ge_4')
LEARNING_RATES = (0.0005, 0.001, 0.002)
CAP_GPU_SECONDS = 24 * 3600
# Measured worst case (100 epochs, all ratings, T4 profiling) plus 25 %; also the session timeout.
BOOKING_SECONDS = {training_run.LIGHTGCN: 2610, training_run.HETERO: 7470}
DEADLINE_MARGIN_SECONDS = 240
SESSION_OVERHEAD_SECONDS = 300
MAX_RUNS = 30
MAX_OUTPUT_BYTES = 1 << 30
MAX_RESULT_BYTES = 64 * 1024 * 1024
CAMPAIGN_APPROVAL_KEYS = {'schema_version', 'campaign_plan_sha256', 'source_bundle_sha256',
                          'dataset_ref', 'dataset_manifest_sha256', 'cap_gpu_seconds',
                          'approved_by', 'approved_on', 'statement'}
REMAINING_GATES = [
    'every planned tuning and final run collected',
    'held-out test evaluation of the selected models, with its own explicit approval',
    'comparative results report reviewed by the user',
]

PROFILE_RUNNER = '"-m", "scripts.profiling_runner"'
PROFILE_ARGS = '''"--device", device,
         "--accelerator", accelerator, "--data", str(data), "--manifest-sha256", MANIFEST_SHA256,
         "--out-dir", str(out)]'''
PROFILE_TITLE = 'Amazon4U Musical_Instruments profiling run {run}. Generated by amazon4u_profile.py'
for _part in (PROFILE_RUNNER, PROFILE_ARGS, PROFILE_TITLE):
    if _part not in KERNEL_TEMPLATE:
        raise ImportError('profiling kernel template changed; the training kernel cannot be derived')
KERNEL = (KERNEL_TEMPLATE
          .replace(PROFILE_TITLE, 'Amazon4U Musical_Instruments training run {run}. Generated by amazon4u_training.py')
          .replace(PROFILE_RUNNER, '"-m", "scripts.training_run"')
          .replace(PROFILE_ARGS, PROFILE_ARGS[:-1] + ''',
         "--checkpoint-dir", tempfile.mkdtemp(prefix="amazon4u-ckpt-"), *RUN_ARGS]'''))
KERNEL = KERNEL.replace('RUNNER_TIMEOUT_SECONDS = {runner_timeout}\n',
                        'RUNNER_TIMEOUT_SECONDS = {runner_timeout}\nRUN_ARGS = {run_args}\n')


def campaign_plan(manifest_sha256):
    """The frozen campaign: 12 tuning runs and the final-run rule."""
    tuning = [{'method': m, 'condition': c, 'learning_rate': lr, 'seed': 42, 'stage': 'tuning'}
              for m in METHODS for c in CONDITIONS for lr in LEARNING_RATES]
    return {'schema_version': SCHEMA_CAMPAIGN, 'protocol_version': training_run.PROTOCOL_VERSION,
            'category': 'Musical_Instruments', 'dataset_manifest_sha256': manifest_sha256,
            'tuning_runs': tuning,
            'final_rule': {'select': 'best_tuning_validation_NDCG@10_per_method_and_condition',
                           'ties': 'earliest_in_learning_rate_order', 'learning_rate_order': list(LEARNING_RATES),
                           'final_seeds': [2026, 3407], 'selected_tuning_run_is_final_seed': 42},
            'cap_gpu_seconds': CAP_GPU_SECONDS, 'booking_seconds': BOOKING_SECONDS}


def plan_sha256(manifest_sha256):
    return _sha256(_canonical(campaign_plan(manifest_sha256)))


def _record_of(reports, run):
    path = Path(reports) / f'run-{run}' / 'record.json'
    return json.loads(path.read_text()) if path.is_file() else None


def collected_runs(reports):
    """{run number: record} for every collected run in the ledger."""
    reports, out = Path(reports), {}
    for path in sorted(reports.glob('run-*.reserved.json')):
        run = int(path.name.split('.')[0].split('-')[1])
        record = _record_of(reports, run)
        if record is not None:
            out[run] = record
    return out


def select_learning_rate(reports, method, condition):
    """The final rule for one group, from its three collected tuning runs; None if incomplete."""
    best = {}
    for record in collected_runs(reports).values():
        s = record['spec']
        if s['stage'] == 'tuning' and (s['method'], s['condition']) == (method, condition):
            best[s['learning_rate']] = record['best_validation_NDCG@10']
    if set(best) != set(LEARNING_RATES):
        return None
    top = max(best.values())
    return next(lr for lr in LEARNING_RATES if best[lr] == top)


def training_ledger(reports):
    """Booked seconds for uncollected runs, recorded runner time plus overhead for collected ones."""
    total = 0
    for path in sorted(Path(reports).glob('run-*.reserved.json')):
        run = int(path.name.split('.')[0].split('-')[1])
        record = _record_of(reports, run)
        total += (record['actual_gpu_seconds'] if record is not None
                  else json.loads(path.read_text())['booked_gpu_seconds'])
    return total


def require_planned(run_spec, manifest_sha256, reports):
    """Refuse a spec outside the frozen plan, or a final run its group has not earned."""
    key = {k: run_spec[k] for k in ('method', 'condition', 'learning_rate', 'seed', 'stage')}
    if run_spec['stage'] == 'tuning':
        if key not in campaign_plan(manifest_sha256)['tuning_runs']:
            raise Amazon4UError('tuning run is not in the frozen campaign plan')
        return
    selected = select_learning_rate(reports, run_spec['method'], run_spec['condition'])
    if selected is None:
        raise Amazon4UError('final runs wait until all three tuning runs of the group are collected')
    if run_spec['learning_rate'] != selected or run_spec['seed'] not in (2026, 3407):
        raise Amazon4UError(f'final runs of this group use learning rate {selected} and seeds 2026, 3407')


def build_bundle(run, run_spec, dataset_ref, manifest_sha256, out_dir, *, root=ROOT, reports=REPORTS):
    if type(run) is not int or not 1 <= run <= MAX_RUNS:
        raise Amazon4UError(f'run must be 1 to {MAX_RUNS}')
    if not _SHA.fullmatch(manifest_sha256):
        raise Amazon4UError('dataset manifest SHA-256 must be 64 lowercase hex characters')
    owner, _, dslug = dataset_ref.partition('/')
    if owner != OWNER or not _SLUG.fullmatch(dslug):
        raise Amazon4UError(f'dataset must be {OWNER}/<slug>')
    full = training_run.spec(run_spec['method'], run_spec['condition'], run_spec['learning_rate'],
                             run_spec['seed'], run_spec['stage'], manifest_sha256)
    require_planned(full, manifest_sha256, reports)
    sources = bundle_sources(root)
    with tempfile.TemporaryDirectory() as tmp:
        for rel, data in sources.items():
            (Path(tmp) / rel).parent.mkdir(parents=True, exist_ok=True)
            (Path(tmp) / rel).write_bytes(data)
        source_digest = bundle_digest(Path(tmp))
    booking = BOOKING_SECONDS[full['method']]
    tag = hashlib.sha256(json.dumps(full, sort_keys=True).encode()).hexdigest()[:8]
    slug = f'amazon4u-train-mi-run-{run}-{tag}'
    run_args = ['--method', full['method'], '--condition', full['condition'],
                '--learning-rate', repr(full['learning_rate']), '--seed', str(full['seed']),
                '--stage', full['stage'], '--runner-seconds', str(booking - DEADLINE_MARGIN_SECONDS)]
    packed = {rel: [_sha256(data), base64.b64encode(gzip.compress(data, mtime=0)).decode()]
              for rel, data in sources.items()}
    kernel = KERNEL.format(run=run, sources=json.dumps(packed, sort_keys=True), manifest_sha=manifest_sha256,
                           runner_timeout=booking - DEADLINE_MARGIN_SECONDS // 2, manifest_name=MANIFEST_NAME,
                           result=training_run.RESULT_NAME, run_args=json.dumps(run_args)).encode()
    metadata = _canonical({
        'id': f'{OWNER}/{slug}', 'title': slug, 'code_file': 'kernel.py', 'language': 'python',
        'kernel_type': 'script', 'is_private': True, 'enable_gpu': True, 'enable_tpu': False,
        'enable_internet': False, 'dataset_sources': [dataset_ref], 'competition_sources': [],
        'kernel_sources': [], 'model_sources': [],
    })
    manifest = {
        'schema_version': SCHEMA_BUNDLE, 'purpose': 'training_mi_v1', 'run': run,
        'kernel_ref': f'{OWNER}/{slug}', 'dataset_ref': dataset_ref,
        'dataset_manifest_sha256': manifest_sha256, 'accelerator': ACCELERATOR,
        'timeout_seconds': booking, 'max_runs': MAX_RUNS, 'max_total_gpu_seconds': CAP_GPU_SECONDS,
        'max_output_bytes': MAX_OUTPUT_BYTES, 'spec': full, 'source_bundle_sha256': source_digest,
        'campaign_plan_sha256': plan_sha256(manifest_sha256),
        'run_binding': {'bundle_sha256': source_digest,
                        'run_spec_sha256': hashlib.sha256(json.dumps(full, sort_keys=True).encode()).hexdigest()},
        'kernel_sha256': _sha256(kernel), 'metadata_sha256': _sha256(metadata),
        'files': {rel: {'sha256': _sha256(data), 'size_bytes': len(data)} for rel, data in sorted(sources.items())},
        'git': _git_state(root),
    }
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=False)
    (out_dir / 'kernel.py').write_bytes(kernel)
    (out_dir / 'kernel-metadata.json').write_bytes(metadata)
    (out_dir / 'bundle.json').write_bytes(_canonical(manifest))
    return manifest


def approver(reports):
    """Accept a per-run approval of this bundle, or the user's campaign approval."""
    def approve(approval, manifest, manifest_sha):
        if manifest.get('purpose') != 'training_mi_v1':
            raise Amazon4UError('not a training bundle')
        require_planned(manifest['spec'], manifest['dataset_manifest_sha256'], reports)
        if type(approval) is dict and approval.get('schema_version') == SCHEMA_APPROVAL:
            return validate_approval(approval, manifest, manifest_sha)
        if type(approval) is not dict or set(approval) != CAMPAIGN_APPROVAL_KEYS \
                or approval['schema_version'] != SCHEMA_CAMPAIGN_APPROVAL or approval['approved_by'] != 'user':
            raise Amazon4UError('approval must be a user per-run or campaign approval')
        for key, want in (('campaign_plan_sha256', manifest['campaign_plan_sha256']),
                          ('source_bundle_sha256', manifest['source_bundle_sha256']),
                          ('dataset_ref', manifest['dataset_ref']),
                          ('dataset_manifest_sha256', manifest['dataset_manifest_sha256']),
                          ('cap_gpu_seconds', CAP_GPU_SECONDS)):
            if approval[key] != want:
                raise Amazon4UError(f'campaign approval {key} does not match this bundle; launch refused')
        if type(approval['statement']) is not str or not approval['statement'].strip():
            raise Amazon4UError('approval must quote the user statement')
    return approve


def check_result(result, out_dir, manifest):
    training_run.validate_result(result, out_dir)
    if result['spec'] != manifest['spec'] or result['run_binding'] != manifest['run_binding']:
        raise Amazon4UError('result spec or binding differs from the pushed bundle')
    env = result['environment']
    if env['device'] != 'cuda:0' or env['used_device_count'] != 1 or env['visible_device_count'] < 1:
        raise Amazon4UError('result must come from exactly one GPU, cuda:0')
    if result['determinism'] != EXPECTED_DETERMINISM:
        raise Amazon4UError('result determinism differs from the fixed policy')


def collect(download_dir, dest, *, manifest, record_fields, log):
    """Check one downloaded training run, add its record and move it to `dest`."""
    download_dir, dest = Path(download_dir), Path(dest)
    if dest.exists():
        raise Amazon4UError(f'{dest} already exists; overwrite refused')
    raw_log = f'{manifest["kernel_ref"].split("/")[1]}.log'
    names = set(os.listdir(download_dir))
    journals = {n for n in names if training_run._PROGRESS.fullmatch(n)}
    allowed = {training_run.RESULT_NAME, training_run.FINAL_NAME, raw_log} | journals
    if not journals or not {training_run.RESULT_NAME, training_run.FINAL_NAME} <= names <= allowed:
        raise Amazon4UError(f'outputs must be result.json, final.a4ucp, progress journals and the log; got {sorted(names)}')
    total = 0
    for name in names:
        info = os.lstat(download_dir / name)
        if not stat.S_ISREG(info.st_mode):
            raise Amazon4UError(f'{name} is not a regular file')
        total += info.st_size
    if total > manifest['max_output_bytes']:
        raise Amazon4UError(f'outputs exceed {manifest["max_output_bytes"]} bytes')
    raw_result = _read_regular(download_dir / training_run.RESULT_NAME, MAX_RESULT_BYTES)
    result = json.loads(raw_result)
    check_result(result, download_dir, manifest)
    if raw_log in names:
        os.unlink(download_dir / raw_log)
    log_bytes = log['logs'].encode()
    with open(download_dir / LOG_NAME, 'xb') as f:
        f.write(log_bytes)
    runner_seconds = 0.0
    for name in sorted(journals):
        records, _, _ = training_run.read_journal(download_dir / name)
        runner_seconds += records[-1].get('elapsed_seconds', 0.0) if records[-1]['event'] == 'end' else 0.0
    record = {
        **record_fields, 'schema_version': SCHEMA_RECORD, 'spec': result['spec'],
        'files': {n: {'sha256': _sha256((download_dir / n).read_bytes()), 'size_bytes': (download_dir / n).stat().st_size}
                  for n in sorted((names - {raw_log}) | {LOG_NAME})},
        'run_binding': manifest['run_binding'], 'environment': result['environment'],
        'result_status': result['status'], 'stop_reason': result['selection']['stop_reason'],
        'selected_epoch': result['selected_epoch'], 'best_validation_NDCG@10': result['best_validation_NDCG@10'],
        'epochs_run': result['epochs_run'], 'runner_seconds': runner_seconds,
        'actual_gpu_seconds': int(runner_seconds) + SESSION_OVERHEAD_SECONDS,
        'test_execution': 'not_run', 'deployment_decision': 'NOT_AUTHORIZED',
        'remaining_gates': list(REMAINING_GATES),
    }
    with open(download_dir / 'record.json', 'xb') as f:
        f.write(_canonical(record))
    atomic_move_no_replace(download_dir, dest)
    return record


def launch(bundle_dir, approval_path, transport, datasets, *, reports=REPORTS, **kw):
    return profile_launch(bundle_dir, approval_path, transport, datasets, reports=reports, collect=collect,
                          approve=approver(reports), ledger=training_ledger, **kw)


def main(argv=None):
    parser = argparse.ArgumentParser(prog='amazon4u_training')
    sub = parser.add_subparsers(dest='command', required=True)
    pl = sub.add_parser('plan')
    pl.add_argument('--manifest-sha256', required=True)
    b = sub.add_parser('bundle')
    b.add_argument('--run', type=int, required=True)
    for name in ('--method', '--condition', '--stage', '--dataset-ref', '--manifest-sha256', '--out'):
        b.add_argument(name, required=True)
    b.add_argument('--learning-rate', type=float, required=True)
    b.add_argument('--seed', type=int, required=True)
    b.add_argument('--reports', default=str(REPORTS))
    lp = sub.add_parser('launch')
    lp.add_argument('--bundle', required=True)
    lp.add_argument('--approval', required=True)
    lp.add_argument('--kaggle', required=True)
    lp.add_argument('--reports', default=str(REPORTS))
    args = parser.parse_args(argv)
    if args.command == 'plan':
        print(json.dumps({'plan': campaign_plan(args.manifest_sha256),
                          'campaign_plan_sha256': plan_sha256(args.manifest_sha256)}, indent=2))
        return 0
    if args.command == 'bundle':
        spec = {'method': args.method, 'condition': args.condition, 'learning_rate': args.learning_rate,
                'seed': args.seed, 'stage': args.stage}
        manifest = build_bundle(args.run, spec, args.dataset_ref, args.manifest_sha256, args.out,
                                reports=args.reports)
        print(json.dumps({'run': manifest['run'], 'kernel_ref': manifest['kernel_ref'],
                          'bundle_manifest_sha256': load_bundle(args.out)[1],
                          'source_bundle_sha256': manifest['source_bundle_sha256'],
                          'campaign_plan_sha256': manifest['campaign_plan_sha256']}, indent=2))
        return 0
    from multiautoresearch.adapters.amazon4u_kaggle import KaggleCliTransport
    record = launch(args.bundle, args.approval, KaggleCliTransport(args.kaggle), KaggleDatasetCli(args.kaggle),
                    reports=args.reports)
    print(json.dumps({'run': record['run'], 'result_status': record['result_status']}))
    return 0


if __name__ == '__main__':
    sys.exit(main())
